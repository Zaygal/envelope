/**
 * Generates the Solidity <-> JavaScript parity vector.
 *
 * Writes test/vectors/parity.json, which test/Parity.t.sol reads with vm.readFile + vm.parseJson
 * and verifies against the DEPLOYED contract code path (PayrollRun.leafFor + OZ MerkleProof).
 *
 * Inputs are fixed (not random) so the vector is reproducible and reviewable in a diff.
 *
 * Run: node scripts/gen-parity-vector.mjs
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildTree, hashLeaf, LEAF_TAG, USDG_DECIMALS } from '../app/lib/merkle.js';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, '../test/vectors/parity.json');

const RUN_ID = 7; // deliberately not 1: catches a hardcoded/ignored runId

/** Fixed, human-readable salts — deterministic so the vector can be checked into git. */
const salt = (n) => '0x' + n.toString(16).padStart(2, '0').repeat(32);

const ROSTER = [
  { claimant: '0x1111111111111111111111111111111111111111', amount: '900',  salt: salt(0x11) },
  { claimant: '0x2222222222222222222222222222222222222222', amount: '400',  salt: salt(0x22) },
  { claimant: '0x3333333333333333333333333333333333333333', amount: '200',  salt: salt(0x33) },
  { claimant: '0x4444444444444444444444444444444444444444', amount: '75.5', salt: salt(0x44) },
  { claimant: '0x5555555555555555555555555555555555555555', amount: '1',    salt: salt(0x55) },
];

const scale = (human) => {
  const [whole, frac = ''] = String(human).split('.');
  const padded = (frac + '0'.repeat(USDG_DECIMALS)).slice(0, USDG_DECIMALS);
  return BigInt(whole) * 10n ** BigInt(USDG_DECIMALS) + BigInt(padded || '0');
};

const leaves = ROSTER.map((r, i) =>
  hashLeaf(RUN_ID, i, r.claimant, scale(r.amount), r.salt),
);
const { root, proofs, depth } = buildTree(leaves);

const total = ROSTER.reduce((acc, r) => acc + scale(r.amount), 0n);

const vector = {
  _comment:
    'Generated by scripts/gen-parity-vector.mjs. Verified against Solidity by test/Parity.t.sol.',
  runId: RUN_ID,
  leafTag: LEAF_TAG,
  depth,
  root,
  total: total.toString(),
  totalHuman: (Number(total) / 10 ** USDG_DECIMALS).toString(),
  leafCount: ROSTER.length,
  entries: ROSTER.map((r, i) => ({
    index: i,
    claimant: r.claimant,
    amountHuman: r.amount,
    amount: scale(r.amount).toString(),
    salt: r.salt,
    leaf: leaves[i],
    proof: proofs[i],
  })),
};

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, JSON.stringify(vector, null, 2) + '\n');

console.log(`wrote ${outPath}`);
console.log(`  runId   ${RUN_ID}`);
console.log(`  leaves  ${ROSTER.length}  (depth ${depth}, so one proof is empty of a sibling)`);
console.log(`  total   ${vector.total}  = ${vector.totalHuman} USDG`);
console.log(`  root    ${root}`);
proofs.forEach((p, i) => console.log(`  proof[${i}] ${p.length} element(s)`));
